// Generates docs/GUIDE.md and docs/PACKAGES.md from the same data the website renders,
// so documentation and site can never drift apart. Run with: pnpm docs:generate
import { writeFileSync } from "node:fs";

import { CHAPTERS, STEPS } from "../modules/curriculum";
import { PACKAGE_GROUPS } from "../modules/toolbox/data/packages";

const out = (name: string, lines: string[]) => {
  writeFileSync(new URL(`../docs/${name}`, import.meta.url), `${lines.join("\n")}\n`);
  process.stdout.write(`Wrote docs/${name}\n`);
};

const guide: string[] = [
  "# The 100-step Git and GitHub command guide",
  "",
  "> Generated by `pnpm docs:generate` from `modules/curriculum/data/guide.ts`. Do not edit by hand.",
  "",
];
for (const chapter of CHAPTERS) {
  guide.push(`## ${chapter.n}. ${chapter.title}`, "", `*${chapter.level}*. ${chapter.summary}`, "");
  for (const step of STEPS.filter((s) => s.chapter === chapter.slug)) {
    guide.push(`### Step ${step.id}: ${step.title}`, "", "```bash", step.command, "```", "", step.explain, "");
    if (step.output) guide.push(`Expected output: \`${step.output}\``, "");
    if (step.tip) guide.push(`> **Tip:** ${step.tip}`, "");
    if (step.danger) guide.push(`> **Warning:** ${step.danger}`, "");
  }
}
out("GUIDE.md", guide);

const total = PACKAGE_GROUPS.reduce((n, g) => n + g.items.length, 0);
const packages: string[] = [
  "# Packages: what each one does and where it is used",
  "",
  "> Generated by `pnpm docs:generate` from `modules/toolbox/data/packages.ts`. Do not edit by hand.",
  "",
  `${total} packages beyond the framework itself. Each has one job and one place in the code, so reading that file is the fastest way to learn it.`,
  "",
  "Rule of thumb: change a package the same way you change code: branch, update, run `pnpm verify`, open a pull request.",
  "",
];
for (const group of PACKAGE_GROUPS) {
  packages.push(`## ${group.title}`, "", group.text, "", "| Package | Purpose | Used in |", "|---|---|---|");
  for (const p of group.items) packages.push(`| \`${p.name}\` | ${p.purpose} | \`${p.usedIn}\` |`);
  packages.push("");
}
out("PACKAGES.md", packages);
